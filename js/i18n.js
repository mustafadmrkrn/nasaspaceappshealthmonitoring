  var STORAGE_KEY = 'sa_lang';
  var lang = 'en';

  function has(code) { return Object.prototype.hasOwnProperty.call(D, code); }

  function t(key, params) {
    var s = D[lang][key];
    if (s === undefined) s = D.en[key];
    if (s === undefined) return key;
    if (!params) return s;
    return s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] !== undefined && params[k] !== null ? String(params[k]) : m; });
  }

  function set(code) {
    if (!has(code)) return false;
    lang = code;
    try { window.localStorage.setItem(STORAGE_KEY, code); } catch (e) { /* storage blocked: language lasts for this page view */ }
    if (typeof document !== 'undefined') document.documentElement.lang = code;
    return true;
  }

  /** Choose the initial language: saved choice, then browser language, then English. */
  function init() {
    var chosen = null;
    try { chosen = window.localStorage.getItem(STORAGE_KEY); } catch (e) { chosen = null; }
    if (!chosen || !has(chosen)) {
      var cands = (typeof navigator !== 'undefined' && (navigator.languages || [navigator.language])) || [];
      for (var i = 0; i < cands.length && (!chosen || !has(chosen)); i++) {
        chosen = String(cands[i] || '').slice(0, 2).toLowerCase();
      }
    }
    lang = has(chosen) ? chosen : 'en';
    if (typeof document !== 'undefined') document.documentElement.lang = lang;
    return lang;
  }

  function get() { return lang; }

  /** For tests: keys missing from, or extra in, a language compared with English. */
  function diff(code) {
    var missing = [], extra = [];
    Object.keys(D.en).forEach(function (k) { if (D[code][k] === undefined) missing.push(k); });
    Object.keys(D[code]).forEach(function (k) { if (D.en[k] === undefined) extra.push(k); });
    return { missing: missing, extra: extra };
  }

  var api = { LANGS: LANGS, DICT: D, t: t, set: set, get: get, init: init, diff: diff };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.I18n = api;
